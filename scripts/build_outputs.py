"""Rebuild the files the website reads, from data/tracker.json.

  data/tracker.js     the data as a script, so index.html also works opened straight from disk
  data/talks.ics   calendar of upcoming appearances (subscribe in Outlook/Google/Apple)
  data/geocache.json  city coordinates for the map (new cities looked up on OpenStreetMap Nominatim)

Run after editing tracker.json by hand:  python scripts/build_outputs.py
"""
from __future__ import annotations

import datetime as dt
import json
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
SKIP_COUNTRIES = {"", "online", "location tbd", "tbd"}


def _load(path, default):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else default


def place_key(city: str, country: str) -> str:
    return f"{city.strip()}|{country.strip()}"


def geocode_missing(apps, geo, enabled=True):
    if not enabled:
        return geo
    import requests
    for a in apps:
        city, country = a.get("city", ""), a.get("country", "")
        key = place_key(city, country)
        if not city or country.lower() in SKIP_COUNTRIES or key in geo:
            continue
        try:
            r = requests.get("https://nominatim.openstreetmap.org/search",
                             params={"q": f"{city}, {country}", "format": "json", "limit": 1},
                             headers={"User-Agent": "LabConferenceTracker/1.0"}, timeout=30)
            hits = r.json()
            if hits:
                geo[key] = [round(float(hits[0]["lat"]), 4), round(float(hits[0]["lon"]), 4)]
        except Exception as e:  # noqa: BLE001
            print(f"geocode failed for {key}: {e}")
        time.sleep(1.1)  # Nominatim usage policy: max 1 request per second
    return geo


def _ics_date(s: str):
    if len(s) == 10:
        return dt.date.fromisoformat(s)
    return None


def _esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,").replace("\n", "\\n")


def build_ics(tracker) -> str:
    # Includes past events too, so the file only changes when the data changes.
    profs = {p["id"]: p for p in tracker["profs"]}
    lines = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//Lab Conference Tracker//EN",
             "CALSCALE:GREGORIAN", "X-WR-CALNAME:Professors of interest: conference talks"]
    for a in sorted(tracker["apps"], key=lambda x: x.get("startDate", "")):
        start = _ics_date(a.get("startDate", ""))
        if not start:
            continue
        end = _ics_date(a.get("endDate", "")) or start
        name = profs.get(a["profId"], {}).get("name", a["profId"])
        place = ", ".join(x for x in (a.get("city"), a.get("country")) if x)
        desc = f'{a.get("role", "")} ({a.get("confidence", "")}). {a.get("notes", "")} Source: {a.get("sourceUrl", "")}'
        lines += ["BEGIN:VEVENT", f'UID:{a["id"]}@lab-conference-tracker',
                  f"DTSTAMP:{start.strftime('%Y%m%d')}T000000Z",
                  f"DTSTART;VALUE=DATE:{start.strftime('%Y%m%d')}",
                  f"DTEND;VALUE=DATE:{(end + dt.timedelta(days=1)).strftime('%Y%m%d')}",
                  f"SUMMARY:{_esc(name)} at {_esc(a.get('conference', ''))}",
                  f"LOCATION:{_esc(place)}", f"DESCRIPTION:{_esc(desc)}", "END:VEVENT"]
    lines.append("END:VCALENDAR")
    return "\r\n".join(lines) + "\r\n"


def main(geocode: bool = True) -> None:
    tracker = _load(DATA / "tracker.json", {"profs": [], "apps": []})
    geo = _load(DATA / "geocache.json", {})
    geo = geocode_missing(tracker["apps"], geo, enabled=geocode)
    (DATA / "geocache.json").write_text(json.dumps(geo, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    payload = dict(tracker)
    payload["geo"] = geo
    # conferences being searched, for the website's Conferences tab
    try:
        import yaml
        wl = yaml.safe_load((ROOT / "watchlist.yaml").read_text(encoding="utf-8")) or {}
        payload["watch"] = [{k: (str(w.get(k)) if k in ("start", "end") and w.get(k) else w.get(k))
                             for k in ("id", "conference", "start", "end", "city", "country", "urls")}
                            | {"enabled": w.get("enabled", True)} for w in wl.get("conferences", []) or []]
    except Exception as e:  # noqa: BLE001
        print(f"could not read watchlist.yaml: {e}")
        payload["watch"] = []
    payload["conferences"] = _load(DATA / "conferences.json", [])
    (DATA / "tracker.js").write_text(
        "// Generated by scripts/build_outputs.py from data/tracker.json. Do not edit by hand.\n"
        "window.TRACKER_DATA = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    (DATA / "talks.ics").write_text(build_ics(tracker), encoding="utf-8", newline="")
    print(f"built tracker.js ({len(tracker['apps'])} appearances) and talks.ics")


if __name__ == "__main__":
    import sys
    main(geocode="--no-geocode" not in sys.argv)
